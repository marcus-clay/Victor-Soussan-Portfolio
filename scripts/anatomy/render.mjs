// Writes the Approche figures: node scripts/anatomy/render.mjs [frame|explore|decide|rhythm]
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, "../../public/images/approche/anatomy");
mkdirSync(OUT, { recursive: true });

const only = process.argv[2];
for (const name of ["frame", "explore", "decide", "rhythm"]) {
  if (only && only !== name) continue;
  let mod;
  try {
    mod = await import(`./${name}.mjs`);
  } catch (error) {
    if (error.code === "ERR_MODULE_NOT_FOUND" && String(error.message).includes(`${name}.mjs`)) continue;
    throw error;
  }
  writeFileSync(join(OUT, `${name}.svg`), mod.svg);
  console.log("wrote", `${name}.svg`, `${(mod.svg.length / 1024).toFixed(0)} KB`);
}

// Static images are cached for a week (next.config headers), so a regenerated figure keeps its old
// look in browsers. Each figure is referenced with a short content hash that changes with the file.
const NAMES = ["frame", "explore", "decide", "rhythm"];
const versions = NAMES.map((name) => {
  try {
    const hash = createHash("sha1").update(readFileSync(join(OUT, `${name}.svg`))).digest("hex").slice(0, 8);
    return `  ${name}: '/images/approche/anatomy/${name}.svg?v=${hash}',`;
  } catch {
    return null;
  }
}).filter(Boolean);
writeFileSync(
  join(HERE, "../../src/data/anatomyAssets.ts"),
  `// Generated by scripts/anatomy/render.mjs: do not edit by hand.\nexport const ANATOMY_SRC = {\n${versions.join("\n")}\n} as const\n`,
);
console.log("wrote src/data/anatomyAssets.ts");
