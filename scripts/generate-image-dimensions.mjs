#!/usr/bin/env node
/**
 * Writes src/data/imageDimensions.ts: the natural width and height of every raster and SVG
 * image under public/. Components pass them as the img width and height attributes, so the
 * browser reserves the right box before a lazy image loads (no layout shift, and anchor
 * scrolling lands where it should).
 *
 * Usage: node scripts/generate-image-dimensions.mjs   (macOS: reads rasters with sips)
 */
import { execFileSync } from 'node:child_process'
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'

const ROOT = 'public'
const RASTER = /\.(webp|png|jpe?g|gif)$/i

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name)
    return statSync(full).isDirectory() ? walk(full) : [full]
  })
}

const files = walk(ROOT)
const dims = {}

// Rasters, in batches (sips prints one block per file, in order)
const rasters = files.filter((f) => RASTER.test(f))
for (let i = 0; i < rasters.length; i += 100) {
  const batch = rasters.slice(i, i + 100)
  const out = execFileSync('sips', ['-g', 'pixelWidth', '-g', 'pixelHeight', ...batch], { encoding: 'utf8', maxBuffer: 1 << 24 })
  let current = null
  for (const line of out.split('\n')) {
    if (line.startsWith('/') || line.startsWith(ROOT)) current = line.trim().replace(/:$/, '')
    const w = line.match(/pixelWidth: (\d+)/)
    const h = line.match(/pixelHeight: (\d+)/)
    if (current && w) (dims[current] ??= [0, 0])[0] = Number(w[1])
    if (current && h) (dims[current] ??= [0, 0])[1] = Number(h[1])
  }
}

// SVGs: width and height attributes, else the viewBox
for (const f of files.filter((f) => /\.svg$/i.test(f))) {
  const head = readFileSync(f, 'utf8').slice(0, 2000)
  const tag = head.match(/<svg\b[^>]*>/i)?.[0] ?? ''
  const w = tag.match(/\swidth="([\d.]+)(px)?"/i)
  const h = tag.match(/\sheight="([\d.]+)(px)?"/i)
  const vb = tag.match(/viewBox="[\d.\-]+[ ,]+[\d.\-]+[ ,]+([\d.]+)[ ,]+([\d.]+)"/i)
  const width = w ? Number(w[1]) : vb ? Number(vb[1]) : 0
  const height = h ? Number(h[1]) : vb ? Number(vb[2]) : 0
  if (width && height) dims[f] = [Math.round(width), Math.round(height)]
}

const entries = Object.entries(dims)
  .filter(([, [w, h]]) => w > 0 && h > 0)
  .map(([f, [w, h]]) => [`/${relative(ROOT, f).split('\\').join('/')}`, [w, h]])
  .sort(([a], [b]) => a.localeCompare(b))

const body = entries.map(([src, [w, h]]) => `  ${JSON.stringify(src)}: [${w}, ${h}],`).join('\n')
writeFileSync(
  'src/data/imageDimensions.ts',
  `// Generated by scripts/generate-image-dimensions.mjs. Do not edit by hand.\n` +
    `export const IMAGE_DIMENSIONS: Record<string, [number, number]> = {\n${body}\n}\n`
)
console.log(`${entries.length} images written to src/data/imageDimensions.ts`)
